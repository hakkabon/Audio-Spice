#!/usr/bin/env bash
# build_xcframework.sh
# Builds the db-Engine Rust FFI crate as an XCFramework and generates
# the Swift UniFFI bindings.
#
# Usage:
#   cd db-Engine
#   ./scripts/build_xcframework.sh
#
# Outputs:
#   XCFrameworks/DbEngineFFI.xcframework  — the binary framework
#   ../db-Lab/Sources/DbEngineFFI/        — generated Swift source files
#
# Requirements:
#   • Rust stable toolchain with aarch64-apple-darwin + x86_64-apple-darwin targets
#   • cargo install uniffi-bindgen  (or: cargo binstall uniffi-bindgen)
#   • Xcode Command Line Tools

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENGINE_DIR="$SCRIPT_DIR/.."
LAB_DIR="$ENGINE_DIR/../db-Lab"
FFI_CRATE="$ENGINE_DIR/crates/ffi"
OUTPUT_DIR="$LAB_DIR/XCFrameworks"
BINDINGS_DIR="$LAB_DIR/Sources/DbEngineFFI"
LIB_NAME="db_engine_ffi"
FRAMEWORK_NAME="DbEngineFFI"

echo "──────────────────────────────────────────────────"
echo "  db-Engine → XCFramework Build Script"
echo "──────────────────────────────────────────────────"

# ── 1. Ensure targets are installed ──────────────────────────────────────────
echo "[1/6] Checking Rust targets…"
rustup target add aarch64-apple-darwin x86_64-apple-darwin 2>/dev/null || true

# ── 2. Build for both Apple Silicon and Intel ─────────────────────────────────
echo "[2/6] Building for aarch64-apple-darwin (release)…"
cargo build -p db-engine-ffi --release --target aarch64-apple-darwin \
    --manifest-path "$ENGINE_DIR/Cargo.toml"

echo "[3/6] Building for x86_64-apple-darwin (release)…"
cargo build -p db-engine-ffi --release --target x86_64-apple-darwin \
    --manifest-path "$ENGINE_DIR/Cargo.toml"

# ── 3. Create fat (universal) library ─────────────────────────────────────────
echo "[4/6] Creating universal (fat) library…"
AARCH64_LIB="$ENGINE_DIR/target/aarch64-apple-darwin/release/lib${LIB_NAME}.a"
X86_64_LIB="$ENGINE_DIR/target/x86_64-apple-darwin/release/lib${LIB_NAME}.a"
FAT_DIR="$ENGINE_DIR/target/universal/release"
mkdir -p "$FAT_DIR"
lipo -create "$AARCH64_LIB" "$X86_64_LIB" -output "$FAT_DIR/lib${LIB_NAME}.a"

# ── 4. Generate Swift bindings ────────────────────────────────────────────────
echo "[5/6] Generating Swift bindings via uniffi-bindgen…"
mkdir -p "$BINDINGS_DIR"

# Try cargo uniffi-bindgen first (uniffi-bindgen-cli), then fall back to
# calling it via the library.
if command -v uniffi-bindgen &>/dev/null; then
    uniffi-bindgen generate \
        --library "$AARCH64_LIB" \
        --language swift \
        --out-dir "$BINDINGS_DIR"
elif cargo uniffi-bindgen --version &>/dev/null 2>&1; then
    cargo uniffi-bindgen generate \
        --library "$AARCH64_LIB" \
        --language swift \
        --out-dir "$BINDINGS_DIR"
else
    echo "⚠️  uniffi-bindgen not found. Install it with:"
    echo "       cargo install uniffi-bindgen"
    echo "   Then re-run this script."
    echo "   Skipping binding generation — the XCFramework will still be built."
fi

# Rename the generated .modulemap if present (Xcode needs the module to match the framework name)
if [ -f "$BINDINGS_DIR/${LIB_NAME}.modulemap" ]; then
    mv "$BINDINGS_DIR/${LIB_NAME}.modulemap" "$BINDINGS_DIR/module.modulemap"
fi

# ── 5. Package into XCFramework ───────────────────────────────────────────────
echo "[6/6] Packaging XCFramework…"
mkdir -p "$OUTPUT_DIR"
XCFW="$OUTPUT_DIR/${FRAMEWORK_NAME}.xcframework"
rm -rf "$XCFW"

# We build a static .xcframework wrapping the fat library + headers.
# The header is generated by uniffi-bindgen (or is empty if skipped).
HEADER_FILE="$BINDINGS_DIR/${LIB_NAME}FFI.h"
if [ ! -f "$HEADER_FILE" ]; then
    # Minimal placeholder header so xcodebuild doesn't complain
    echo "// Auto-generated UniFFI header placeholder" > "$HEADER_FILE"
fi

xcodebuild -create-xcframework \
    -library "$FAT_DIR/lib${LIB_NAME}.a" \
    -headers "$BINDINGS_DIR" \
    -output "$XCFW"

echo ""
echo "✅ Done!"
echo "   XCFramework: $XCFW"
echo "   Swift sources: $BINDINGS_DIR"
echo ""
echo "Next steps:"
echo "  1. Uncomment the DbEngineFFI target + binaryTarget in db-Lab/Package.swift"
echo "  2. Add .define(\"UNIFFI_AVAILABLE\") to the swiftSettings"
echo "  3. Update EngineClient.swift to call the real CrossoverEngine/CircuitEngine"
